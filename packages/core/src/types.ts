// ─── Issuing Organization ────────────────────────────────────────────────────

export type SoulboundOrgType =
  | "DAO"          // Decentralized autonomous organization
  | "CLUB"         // Sports, social, cultural club
  | "HOSPITAL"     // Hospital, clinic, medical center
  | "UNIVERSITY"   // University, academy, institute
  | "CORP"         // Private company (employees, partners)
  | "COOPERATIVE"  // Cooperative, union
  | "GOVERNMENT"   // Government agency
  | "OTHER";

export interface SoulboundIssuer {
  orgId: string;          // PolicyId of the issuer on Cardano
  orgName: string;        // e.g. "ALDEA DAO"
  orgType: SoulboundOrgType;
  publicKey: string;      // Issuer's public key (signature verification)
}

// ─── Credential ──────────────────────────────────────────────────────────────

export type SoulboundCredentialStatus =
  | "PENDING"   // Issued by org, not yet claimed by holder
  | "CLAIMED"   // Claimed by holder
  | "REVOKED"   // Revoked by issuer
  | "EXPIRED";  // Expired (expiresAt < now)

export type SoulboundSchemaId =
  | "soulbound:v1:membership"    // General organization membership
  | "soulbound:v1:certificate"   // Achievement/completion certificate
  | "soulbound:v1:professional"  // Professional credential
  | "soulbound:v1:access";       // Service/platform access credential

export interface SoulboundCredential {
  // Schema identification
  schemaId: SoulboundSchemaId;
  schemaVersion: string;         // "1.0.0"

  // Issuing organization
  issuer: SoulboundIssuer;

  // Holder data (shielded in Midnight — never exposed publicly)
  subject: {
    walletHash: string;          // Hash of the wallet (not the public address)
    usernameHash?: string;       // SHA-256 hash of username (selectively disclosable)
    memberId?: string;           // Internal org ID (encrypted)
    metadata?: Record<string, unknown>; // Extra data (shielded)
  };

  // Validity
  issuedAt: number;              // Unix timestamp
  expiresAt?: number;            // Unix timestamp (undefined = never expires)

  // Status
  status: SoulboundCredentialStatus;

  // Fields the holder can selectively disclose in a ZK Proof
  disclosureFields: string[];

  // Issuer's signature over the credential hash
  credentialProof: string;
}

