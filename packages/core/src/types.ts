// ─── ZK Proofs ───────────────────────────────────────────────────────────────

export interface SoulboundMembershipProof {
  // The proof itself (opaque — generated by Midnight ZK circuit)
  proofData: string;

  // Fields selectively disclosed by the holder
  disclosedFields: Record<string, unknown>;

  // Proof metadata (contains no holder data)
  resourceId: string;      // The resource being accessed
  expectedOrgId: string;   // PolicyId of the expected issuer
  nonce: string;           // Prevents replay attacks
  generatedAt: number;     // Unix timestamp
}

export interface SoulboundProofVerificationResult {
  isValid: boolean;
  orgId?: string;           // Only if disclosed
  resourceId: string;
  verifiedAt: number;
}

// ─── Emit/Mint Input ─────────────────────────────────────────────────────────

export interface SoulboundEmitInput {
  schema: SoulboundSchemaId;
  subject: {
    walletAddress: string;   // Public address (hashed internally before storing)
    username?: string;       // Plaintext username (hashed internally before storing)
    resourceId?: string;     // For "soulbound:v1:access" schema
    accessLevel?: string;    // For "soulbound:v1:access" schema
    memberId?: string;
    memberSince?: number;
    tier?: string;
    achievementName?: string;
    grade?: string;
    courseId?: string;
    professionCode?: string;
    licenseNumber?: string;
    specialty?: string;
    issuingAuthority?: string;
  };
  expiresAt?: Date;
}

// ─── Public Mint (ADA payment) ───────────────────────────────────────────────

export interface SoulboundPublicMintRequest {
  walletAddress: string;
  paymentTxHash: string;     // Cardano payment tx hash
  paymentAmount: bigint;     // In Lovelace
}

export interface SoulboundPublicMintResult {
  credentialId: string;
  txHash: string;            // Midnight issuance tx
  status: "PENDING";
}

